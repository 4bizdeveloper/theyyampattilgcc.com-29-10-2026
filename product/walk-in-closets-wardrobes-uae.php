        <!-- Section 5: Buying Guide -->
        <section>
            <h2 class="section-title">How Do You Choose the Right Closet or Wardrobe for Your Home?</h2>
            <p class="section-intro">Start by deciding whether you have space for a dedicated walk-in closet or need a wardrobe fitted into an existing bedroom. From there, the same core factors apply to both: storage inventory, open vs. concealed style, room for future growth, lighting, and specifically for walk-in rooms traffic flow around any islands.</p>

            <div class="buying-guide-grid">
                <div class="guide-card">
                    <h3>Should you choose a walk-in closet or a fitted wardrobe?</h3>
                    <p>A walk-in closet needs dedicated room space but offers a more immersive dressing-room feel; a built-in or sliding wardrobe fits into an existing bedroom wall and suits smaller homes. If your bedroom can't spare a separate room, a wardrobe delivers most of the same storage benefit within the existing footprint.</p>
                </div>
                <div class="guide-card">
                    <h3>What should you inventory before designing either option?</h3>
                    <p>Shoes, folded items, hanging garments, and accessories each need different storage types. Listing out what you own and how much of it before design begins prevents a beautiful system that runs out of space within a year.</p>
                </div>
                <div class="guide-card">
                    <h3>Should you choose open, concealed, or mixed storage?</h3>
                    <p>Open shelving suits those who enjoy displaying a curated wardrobe, while concealed storage suits those who prefer a calm, clutter-free room. Most luxury systems blend both open sections for daily items, concealed cabinetry for the rest.</p>
                </div>
                <div class="guide-card">
                    <h3>Sliding or hinged doors - which is right for a wardrobe?</h3>
                    <p>Sliding wardrobes save floor space and suit smaller rooms, since the doors don't swing outward; hinged doors on open or concealed systems often allow more interior configuration.</p>
                </div>
                <div class="guide-card">
                    <h3>How do you plan for future wardrobe growth?</h3>
                    <p>Adjustable shelving and modular drawer systems let the space adapt over time, rather than needing a full redesign every few years.</p>
                </div>
                <div class="guide-card">
                    <h3>Why does lighting matter in closet and wardrobe design?</h3>
                    <p>Integrated LED lighting inside cabinets and along shelving isn't just aesthetic - it makes it easier to actually see and choose what you're storing, especially in concealed sections.</p>
                </div>
                <div class="guide-card">
                    <h3>How much clearance does a walk-in closet actually need?</h3>
                    <p>Islands, vanity units, and central storage look striking but need enough clearance around them. Getting proportions right at the design stage avoids a closet that feels cramped once installed. (This applies specifically to dedicated walk-in rooms, not fitted wardrobes.)</p>
                </div>
            </div>
        </section>

