    <div class="text-block">
        <h2>5. What Happens if Something Needs Adjustment After Installation?</h2>
        <h3>Why This Question Matters</h3>
        <p>Even with precise measurements, minor adjustments (a door alignment, a drawer glide, a panel gap) sometimes come up after installation. A furniture maker's after-sales policy tells you a lot about how seriously they stand behind their work.</p>
        <p><strong>What to listen for:</strong> A clear warranty or after-sales support policy, not just a one-time sale-and-done relationship.</p>
    </div>

