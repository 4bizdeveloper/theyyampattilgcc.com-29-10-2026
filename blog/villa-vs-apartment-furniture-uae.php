        <h3>Materials Can Be More Ambitious</h3>
        <p>With more space and typically higher budgets, villa furniture often uses premium natural materials - solid wood, natural stone finishes, and full-grain leathers - since there's room to let a single statement piece anchor a whole room.</p>

