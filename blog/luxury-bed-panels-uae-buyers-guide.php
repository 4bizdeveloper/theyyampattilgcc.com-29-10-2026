            <p>A standard headboard is attached to the bed. A bed panel is a wall treatment behind it, designed to the width and height of the wall, and it often carries lighting, side units, and decorative detail. It turns the headboard wall into the focal point of the room.</p>
            <h3>Where It Fits in the Bedroom Layout</h3>
            <p>The bed panel anchors the layout: the wardrobes, dressing area, and any TV wall are easier to plan once the headboard wall is defined. Decide it early in the design.</p>
