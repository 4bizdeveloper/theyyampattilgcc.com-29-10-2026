            <h3>Lighting</h3>
            <p>Warm LED strips behind or around the panel, wall-mounted reading lights, and dimmable ambient lighting set a relaxing atmosphere. Plan the cabling and drivers at design stage so everything is concealed.</p>
            <h3>Bedside Units and Power</h3>
            <p>Floating bedside units, built-in shelves, and concealed sockets and USB points keep the area tidy and practical. Decide socket positions before the panel is made.</p>
