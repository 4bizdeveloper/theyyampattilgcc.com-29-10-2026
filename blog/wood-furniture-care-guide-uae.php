                <h2>1. Protect Furniture from Direct Sunlight</h2>
                <h3>The Risk</h3>
                <p>Dubai's sun is intense enough to fade wood finishes, dry out natural oils in the wood, and cause uneven discoloration on surfaces exposed to direct light versus shaded areas.</p>
                <h3>What to Do</h3>
                <p>Position wood furniture away from direct window exposure where possible, or use UV-filtering window film or curtains during peak sun hours. Rotate smaller pieces occasionally so fading, if it happens, stays even rather than patchy.</p>
