            <h2>5. Keep Furniture Away from AC Vents and Heat Sources</h2>
            <h3>The Risk</h3>
            <p>Direct, concentrated airflow from AC vents dries wood unevenly and faster than general room air, often causing cracking specifically in the area closest to the vent.</p>
            <h3>What to Do</h3>
            <p>Position large wood pieces - dining tables, wardrobes, headboards - away from direct vent airflow. If repositioning isn't possible, consider a vent deflector to redirect airflow away from the furniture surface.</p>
