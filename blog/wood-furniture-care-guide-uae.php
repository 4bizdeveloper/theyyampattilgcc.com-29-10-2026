                <h2>2. Manage Indoor Humidity Levels</h2>
                <h3>The Risk</h3>
                <p>Constant air conditioning keeps indoor air very dry, which can cause wood to lose moisture, shrink slightly, and develop small cracks particularly at joints and seams where different wood pieces meet.</p>
                <h3>What to Do</h3>
                <p>Maintain indoor humidity between 40-60% where possible, using a humidifier in heavily air-conditioned rooms. Avoid placing wood furniture directly beneath AC vents, where airflow is most concentrated and drying.</p>
            </div>
            <div class="row-image">
